export function icon(name, attrs = '') {
  const body = P[name] ?? P.info;
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" ${attrs}>${body}</svg>`;
}

/** Иконка категории по MCC — для истории операций. */
export function mccIcon(mcc) {
  const g = groupOf(mcc);
  if (g === 'topup') return icon('arrowDown');
  if (g === 'piggy') return icon('jar');
  if (g === 'cashback') return icon('sparkles');
  return icon(category(g)?.icon ?? 'receipt');
}

/**
 * Иконка банка. Официальный файл кладётся в assets/icon.png;
 * если его нет, подставляется векторный знак (обработчик ошибки — в main.js).
 */
export function bankIcon(size = 40) {
  if (bankIconMissing) return mobyMark(size, 'bank-icon');
  return `<img class="bank-icon" src="${BANK_ICON_URL}" width="${size}" height="${size}" alt="МТБанк" data-fallback="bank" />`;
}

export const BANK_ICON_URL = 'assets/icon.png';
let bankIconMissing = false;
/** Вызывается, если assets/icon.png не найден — дальше рисуем векторный знак без лишних запросов. */
export function markBankIconMissing() {
  bankIconMissing = true;
}

